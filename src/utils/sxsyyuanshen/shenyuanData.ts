export function parseEnemy(token: string): ShenyuanEnemy {
    const matched = token.match(/^(.+?)\*(\d+)$/);
    return matched ? { name: matched[1].trim(), count: Number(matched[2]) } : { name: token, count: 1 };
}

export function formatEnemy(enemy: ShenyuanEnemy) {
    return enemy.count > 1 ? `${enemy.name} ×${enemy.count}` : enemy.name;
}

export function enemiesOf(item: ShenyuanPeriod, room: 1 | 2 | 3, half: "up" | "down") {
    return (item[half][room - 1] || []).map(parseEnemy);
}

export function buffText(buff: ShenyuanBuff) {
    return Array.isArray(buff) ? `上半：${buff[0]}、下半：${buff[1]}` : buff;
}

