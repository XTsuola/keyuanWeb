export type ShenyuanBuff = string | [string, string];

export interface ShenyuanEnemy {
    name: string;
    count: number;
}

export interface ShenyuanPeriod {
    period: number;
    version: string;
    buff: ShenyuanBuff;
    up: ShenyuanRooms;
    down: ShenyuanRooms;
}

