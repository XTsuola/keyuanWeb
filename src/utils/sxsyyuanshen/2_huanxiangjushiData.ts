export function jushiBosses(item: JushiPeriod) {
    return item.boss.map((name, index) => ({
        floor: jushiFloors[index] ?? `第${index + 1}项`,
        name,
        units: name.split("、").map((unit) => unit.trim()).filter(Boolean),
    }));
}

