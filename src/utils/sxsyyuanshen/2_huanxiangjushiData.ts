/**
 * 幻想真境剧诗
 * id：ID序号
 * name: 第N期
 * limit：限制属性，其中 3 个
 * boss：依次为 3间、6间、8间、10间、圣牌1、圣牌2
 */
export type JushiElement = "火" | "水" | "雷" | "冰" | "草" | "风" | "岩";

export interface JushiPeriod {
    id: number;
    name: string;
    limit: JushiElement[];
    boss: string[];
}

export const jushiFloors = ["3间", "6间", "8间", "10间", "圣牌1", "圣牌2"];

