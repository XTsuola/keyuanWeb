/**
 * 圣遗物
 * id：ID序号
 * name: 套装名称
 * quality：品质 1.蓝色3星、2.紫色4星、3.橙色5星
 * two：两件套效果（如果是祭X之人，是单件套）
 * four：四件套效果
 * text：介绍，分别是：生之花、死之羽、时之沙、空之杯、理之冠（[部位名称，简介]）
 */

export type ShengyiwuQuality = 1 | 2 | 3;

export interface ShengyiwuSet {
    id: number;
    name: string;
    quality: ShengyiwuQuality;
    two: string;
    four: string;
    text: [string, string][];
}

export const shengyiwuQualities: { id: ShengyiwuQuality; name: string; color: string }[] = [
    { id: 1, name: "蓝色3星", color: "#1677ff" },
    { id: 2, name: "紫色4星", color: "#722ed1" },
    { id: 3, name: "橙色5星", color: "#d48806" },
];

export const shengyiwuSlots = ["生之花", "死之羽", "时之沙", "空之杯", "理之冠"] as const;

export function isSingleSet(item: ShengyiwuSet) {
    return /^祭.之人$/.test(item.name);
}

export function shengyiwuPieces(item: ShengyiwuSet) {
    return item.text
        .map((piece, index) => ({
            slot: shengyiwuSlots[index] ?? `部位${index + 1}`,
            name: piece[0],
            info: piece[1],
        }))
        .filter((piece) => piece.name !== "/" && piece.info !== "/");
}

